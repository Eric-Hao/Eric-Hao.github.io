"""Read-only checks for the English Research Lab rebuild (Python stdlib only)."""
from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit, unquote
import json, re, sys
import build_editorial as build

class Document(HTMLParser):
 def __init__(self, text):
  super().__init__(convert_charrefs=True); self.ids=[]; self.refs=[]; self.images=[]; self.tags=[]; self.text=[]; self.feed(text)
 def handle_starttag(self, tag, attrs):
  attrs=dict(attrs); self.tags.append((tag,attrs))
  if attrs.get('id'): self.ids.append(attrs['id'])
  for field in ('href','src'):
   if attrs.get(field): self.refs.append((tag,field,attrs[field]))
  if tag=='img': self.images.append(attrs)
 def handle_data(self, text): self.text.append(text)

def verify():
 root=build.ROOT; failures=[]; checks=0
 def check(ok,message):
  nonlocal checks; checks+=1
  if not ok: failures.append(message)
 catalog=build.CATALOG; baseline=json.loads((root/'_content/tests/route-baseline.json').read_text())['routes']
 check({p['image']:p['article'] for p in catalog}==baseline,'Existing article routes changed')
 records={p['image']:build.validate(json.loads((build.CONTENT/f'{p["image"]}.json').read_text())) for p in catalog}
 pages=[root/'index.html']+[root/p['article']/'index.html' for p in catalog]
 docs={p:Document(p.read_text()) for p in pages}
 for path,doc in docs.items():
  raw=path.read_text(); text=' '.join(doc.text)
  check(not re.search('[\u4e00-\u9fff]',text),f'{path}: Chinese visible text')
  check(len(doc.ids)==len(set(doc.ids)),f'{path}: duplicate IDs')
  check(sum(t=='h1' for t,a in doc.tags)==1,f'{path}: expected one h1')
  check('Learning to reason.' not in raw and 'hero-particle' not in raw,f'{path}: removed hero remains')
  check(not re.search(r'katex-error|data-math=',raw),f'{path}: math failed or unrendered')
  check('lang="en"' in raw,f'{path}: missing English language')
  for img in doc.images: check('alt' in img,f'{path}: image missing alt')
  for tag,field,url in doc.refs:
   parsed=urlsplit(url)
   if parsed.scheme:
    check(parsed.scheme in ('https','http'),f'{path}: unsafe URL {url}');continue
   target=(path.parent/unquote(parsed.path)).resolve() if parsed.path else path
   if parsed.path.startswith('/'):
    target=(root.parent/parsed.path.lstrip('/')).resolve()
   if target.is_dir(): target=target/'index.html'
   # Academic homepage is generated by Jekyll, outside this standalone check.
   if target==root.parent/'index.html':continue
   check(target.exists(),f'{path}: missing local target {url}')
   if parsed.fragment and target.suffix=='.html' and target.exists():
    target_doc=docs.get(target) or Document(target.read_text())
    check(unquote(parsed.fragment) in target_doc.ids,f'{path}: missing anchor {url}')
 for paper in catalog:
  r=records[paper['image']]; doc=docs[root/paper['article']/'index.html']
  check(any(t=='details' and a.get('class')=='mobile-contents' for t,a in doc.tags),f'{paper["image"]}: mobile contents missing')
  words=len(' '.join(p for s in r['sections'] for p in s['paragraphs']).split())
  if r['status']=='complete':
   check(words>=600,f'{paper["image"]}: article too short ({words})')
   check(bool(r.get('evidence')),f'{paper["image"]}: no evidence map')
   check(any(s.get('figure') for s in r['sections']),f'{paper["image"]}: no source figure')
   check(len(r['sections'])>=4,f'{paper["image"]}: incomplete story')
  else:
   check(paper['image']=='vortex-bursting',f'{paper["image"]}: unexpected source gap')
   check('source-notice' in (root/paper['article']/'index.html').read_text(),'Source-gap notice missing')
 index=docs[root/'index.html']
 check(sum('data-search' in a for t,a in index.tags)==22,'Index missing papers')
 check(sum(a.get('class')=='research-card' for t,a in index.tags)==22,'Unified index should have all 22 entries')
 check(len(build.COVERS)==22,'All 22 entries must have new illustrations')
 check(sum('data-view' in a for t,a in index.tags)==2,'Grid/list controls missing')
 check(sum(a.get('name')=='sort' for t,a in index.tags)==4,'Expected four sort choices')
 for control in ('filter-panel','sort-panel','research-search','clear-all'):
  check(control in index.ids,f'Index control missing: {control}')
 for p in catalog:
  doc=docs[root/p['article']/'index.html']
  check(any(t=='div' and a.get('class')=='article-banner' for t,a in doc.tags),f'{p["image"]}: article banner missing')
 for key,cover in build.COVERS.items():
  check(cover['thumbnail'].startswith('images/covers-index-2026/'),f'{key}: artwork was not redrawn')
  check((root/cover['thumbnail']).is_file(),f'{key}: new cover missing')
 css=(root/'site.css').read_text()
 check('grid-template-columns:repeat(4,minmax(0,1fr))' in css,'Four-column desktop panel layout missing')
 check('<footer' not in (root/'index.html').read_text(),'Unwanted footer remains')
 check('.research-results[data-layout=list]' in css,'List view missing')
 check("'PingFang SC'" in css and "'Microsoft YaHei'" in css,'CJK sans-serif fallbacks missing')
 check('--paper:#fff' in css,'White research canvas missing')
 check('.article-hero{container-type:inline-size' in css,'Measured full-bleed hero missing')
 check('grid-template-columns:1fr;gap:80px 24px' in css,'Single-column mobile panel layout missing')
 check('search-toggle' not in (root/'index.html').read_text(),'Extra index search control remains')
 check((root/'site.css').read_text()==(root/'_content/styles/research.css').read_text(),'CSS source differs from output')
 font_css=(root/'fonts/openai/openai-fonts.css').read_text()
 font_files=re.findall(r'url\("\./([^\"]+)"\)',font_css)
 check(len(font_files)==141,'Expected 10 Latin faces and 131 SC subsets')
 for name in font_files:
  font=root/'fonts/openai'/name
  check(font.exists() and font.read_bytes()[:4]==b'wOF2',f'Invalid webfont: {name}')
 report={'checks':checks,'passed':checks-len(failures),'failures':failures,'pages':len(pages),'complete_articles':sum(r['status']=='complete' for r in records.values()),'source_gaps':[k for k,r in records.items() if r['status']!='complete'],'words':sum(len(' '.join(p for s in r['sections'] for p in s['paragraphs']).split()) for r in records.values())}
 print(json.dumps(report,indent=2))
 if failures:sys.exit(1)
 return report
if __name__=='__main__':verify()
